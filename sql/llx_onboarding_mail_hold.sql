-- Emails held until the approver says they may go (Member onboarding setup,
-- Email approval). Kept 90 days after they are decided.
CREATE TABLE llx_onboarding_mail_hold(
	rowid integer AUTO_INCREMENT PRIMARY KEY NOT NULL,
	entity integer DEFAULT 1 NOT NULL,
	kind varchar(190) NOT NULL,
	token varchar(64) NOT NULL,
	status varchar(16) DEFAULT 'pending' NOT NULL,
	mail_from varchar(255),
	mail_to text,
	mail_cc text,
	mail_bcc text,
	reply_to varchar(255),
	errors_to varchar(255),
	subject varchar(255),
	body mediumtext,
	ishtml integer DEFAULT 0 NOT NULL,
	css text,
	trackid varchar(255),
	sendcontext varchar(32),
	deliveryreceipt integer DEFAULT 0 NOT NULL,
	files text,
	notified integer DEFAULT 0 NOT NULL,
	decided_by varchar(255),
	decided_at datetime,
	error varchar(255),
	datec datetime,
	tms timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=innodb;
